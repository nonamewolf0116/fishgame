export async function loadFishSpriteSheet() {
  const image = await loadImage(spriteSheetSrc);
  return removeBackground(image, { r: 235, g: 194, b: 117 }, 30);
}

export function drawFish(ctx, spriteSheet, sprite, x, y, width = sprite.width, height = sprite.height) {
  ctx.drawImage(
    spriteSheet,
    sprite.x,
    sprite.y,
    sprite.width,
    sprite.height,
    x,
    y,
    width,
    height
  );
}

function loadImage(src) {
  return new Promise((resolve, reject) => {
    const image = new Image();
    image.onload = () => resolve(image);
    image.onerror = reject;
    image.src = src;
  });
}

function removeBackground(image, bg, tolerance) {
  const canvas = document.createElement('canvas');
  canvas.width = image.width;
  canvas.height = image.height;

  const ctx = canvas.getContext('2d');
  ctx.drawImage(image, 0, 0);

  const imageData = ctx.getImageData(0, 0, canvas.width, canvas.height);
  const data = imageData.data;
  const limit = tolerance * tolerance;

  for (let i = 0; i < data.length; i += 4) {
    const dr = data[i] - bg.r;
    const dg = data[i + 1] - bg.g;
    const db = data[i + 2] - bg.b;
    if (dr * dr + dg * dg + db * db <= limit) {
      data[i + 3] = 0;
    }
  }

  ctx.putImageData(imageData, 0, 0);
  return canvas;
}
